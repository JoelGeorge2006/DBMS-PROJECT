-- 8a. One row per mine for the map, the mines table and the API
CREATE VIEW v_mines_master AS
SELECT
    m.mine_id,
    m.mine_name,
    min.mineral_name AS primary_mineral,
    min.mineral_type,
    co.commodity_name,
    mm.ore_grade_description,
    s.state_name AS state,
    l.district,
    s.state_name || ', ' || l.district AS state_district,
    l.craton_region,
    c.company_name AS operating_lessee,
    c.company_type,
    CASE WHEN le.lease_id IS NOT NULL
         THEN to_char(le.execution_date, 'YYYY') || ' — ' || to_char(le.valid_till, 'YYYY') END AS lease_validity,
    le.lease_id,
    le.execution_date,
    le.valid_till,
    le.royalty_rate_pct,
    CASE WHEN le.lease_id IS NOT NULL
         THEN to_char(le.lease_area_hectares, 'FM999,999,990.00') || ' Hectares' END AS area_formatted,
    le.lease_area_hectares,
    le.forest_clearance_stage,
    le.cto_valid_till,
    m.status,
    m.mine_type,
    m.latitude,
    m.longitude,
    m.location_precision,
    m.is_sample,
    m.source_ref,
    m.source_url,
    ds.name AS source_name,
    ds.licence AS source_licence,
    min.fe_pct,
    min.sio2_pct,
    min.al2o3_pct,
    min.phosphorus_pct,
    min.moisture_pct
FROM mine m
JOIN location l ON l.location_id = m.location_id
JOIN state s ON s.state_id = l.state_id
JOIN data_source ds ON ds.source_id = m.source_id
LEFT JOIN mining_company c ON c.company_id = m.company_id
LEFT JOIN lease le ON le.lease_id = m.lease_id
LEFT JOIN mine_mineral mm ON mm.mine_id = m.mine_id AND mm.is_primary
LEFT JOIN mineral min ON min.mineral_id = mm.mineral_id
LEFT JOIN commodity co ON co.commodity_id = min.commodity_id;
COMMENT ON VIEW v_mines_master IS 'One row per mine with its location, primary mineral, company and lease';

-- 8b. Mines per district and mineral
CREATE VIEW v_district_mineral_occurrence AS
SELECT
    s.state_name AS state,
    l.district,
    min.mineral_name,
    COUNT(DISTINCT m.mine_id) AS total_mines,
    SUM(le.lease_area_hectares) AS total_concession_area,
    SUM(p.quantity_mt) AS total_extraction_2024_mt
FROM location l
JOIN state s ON s.state_id = l.state_id
JOIN mine m ON m.location_id = l.location_id
JOIN mine_mineral mm ON mm.mine_id = m.mine_id
JOIN mineral min ON min.mineral_id = mm.mineral_id
LEFT JOIN lease le ON le.lease_id = m.lease_id
LEFT JOIN production p ON p.mine_id = m.mine_id AND p.fiscal_year = 2024
GROUP BY s.state_name, l.district, min.mineral_name;
COMMENT ON VIEW v_district_mineral_occurrence IS 'Mines, lease area and 2024 output per district and mineral';

-- 8c. Yearly output per state (sample production records)
CREATE VIEW v_cross_state_production AS
SELECT
    s.state_name AS state,
    p.fiscal_year,
    COUNT(DISTINCT m.mine_id) AS active_mines_count,
    ROUND(SUM(p.quantity_mt), 2) AS total_extracted_mt,
    ROUND(SUM(p.dispatch_mt), 2) AS total_dispatched_mt,
    ROUND(SUM(p.dispatch_mt) * 100.0 / NULLIF(SUM(p.quantity_mt), 0), 1) AS dispatch_efficiency_pct
FROM production p
JOIN mine m ON m.mine_id = p.mine_id
JOIN location l ON l.location_id = m.location_id
JOIN state s ON s.state_id = l.state_id
GROUP BY s.state_name, p.fiscal_year;
COMMENT ON VIEW v_cross_state_production IS 'Extraction and dispatch per state and year';

