    le.forest_clearance_stage,
    le.cto_valid_till,
    ROUND(((le.valid_till - CURRENT_DATE) / 365.25)::numeric, 1) AS years_remaining,
    CASE
        WHEN le.valid_till <= CURRENT_DATE + INTERVAL '1 year' THEN 'Renewal due within 1 year'
        WHEN le.valid_till <= CURRENT_DATE + INTERVAL '5 years' THEN 'Renewal due within 5 years'
        ELSE 'More than 5 years left'
    END AS compliance_risk_tier
FROM lease le
JOIN mine m ON m.lease_id = le.lease_id
LEFT JOIN mining_company c ON c.company_id = le.company_id;
COMMENT ON VIEW v_lease_lifecycle_compliance IS 'Years left on each lease and its renewal tier';

-- 8e. Each state's mining profile; ranks use a window function
CREATE VIEW v_state_mining_profile AS
WITH value_2223 AS (
    SELECT state_id, value_rs_crore FROM state_production_value WHERE fiscal_year = '2022-23'
),
leases AS (
    SELECT state_id, lease_count, lease_area_ha FROM state_mining_lease_stat WHERE as_on = DATE '2023-03-31'
),
reporting AS (
    SELECT state_id, reporting_mines FROM state_reporting_mines WHERE fiscal_year = '2022-23'
),
mapped AS (
    SELECT l.state_id, COUNT(*) AS mines_on_map
    FROM mine m JOIN location l ON l.location_id = m.location_id
    GROUP BY l.state_id
),
auctions AS (
    SELECT state_id, COUNT(*) AS blocks_auctioned FROM block_auction GROUP BY state_id
)
SELECT
    s.state_name,
    v.value_rs_crore AS production_value_2022_23_crore,
    ROUND(100.0 * v.value_rs_crore / NULLIF(SUM(v.value_rs_crore) OVER (), 0), 2) AS share_of_india_pct,
    CASE WHEN v.value_rs_crore > 0 THEN RANK() OVER (ORDER BY v.value_rs_crore DESC NULLS LAST) END AS value_rank,
    le.lease_count,
    le.lease_area_ha,
    r.reporting_mines AS reporting_mines_2022_23,
    COALESCE(mp.mines_on_map, 0) AS mines_on_map,
    COALESCE(a.blocks_auctioned, 0) AS critical_blocks_auctioned
FROM state s
LEFT JOIN value_2223 v ON v.state_id = s.state_id
LEFT JOIN leases le ON le.state_id = s.state_id
LEFT JOIN reporting r ON r.state_id = s.state_id
LEFT JOIN mapped mp ON mp.state_id = s.state_id
LEFT JOIN auctions a ON a.state_id = s.state_id;
COMMENT ON VIEW v_state_mining_profile IS 'Per state: production value and rank, leases, reporting mines, mapped mines, auctions';

-- 8f. Each commodity across every dataset
CREATE VIEW v_commodity_overview AS
SELECT
    co.commodity_name,
    co.category,
    co.is_critical,
    (SELECT ROUND(SUM(np.value_rs_thousand) / 10000, 1)
       FROM national_production np JOIN mineral_product mp ON mp.product_id = np.product_id
      WHERE mp.commodity_id = co.commodity_id AND np.fiscal_year = '2023-24') AS production_value_2023_24_crore,
    (SELECT string_agg(r.rate_text, '; ' ORDER BY r.grade)
       FROM royalty_rate r
      WHERE r.commodity_id = co.commodity_id
        AND r.schedule_year = (SELECT MAX(schedule_year) FROM royalty_rate WHERE commodity_id = co.commodity_id)) AS current_royalty,
    (SELECT COUNT(*) FROM mineral_reserve mr WHERE mr.commodity_id = co.commodity_id) AS reserve_rows,
    (SELECT SUM(cl.lease_count) FROM commodity_mining_lease_stat cl WHERE cl.commodity_id = co.commodity_id) AS mining_leases,
    (SELECT COUNT(DISTINCT mm.mine_id)
       FROM mine_mineral mm JOIN mineral mi ON mi.mineral_id = mm.mineral_id
      WHERE mi.commodity_id = co.commodity_id) AS mines_on_map,
    (SELECT COUNT(*) FROM block_auction_commodity bc WHERE bc.commodity_id = co.commodity_id) AS blocks_auctioned
FROM commodity co;
COMMENT ON VIEW v_commodity_overview IS 'Per commodity: production value, current royalty, reserves, leases, mines and auctions';

-- 8g. Auction results with their minerals
CREATE VIEW v_auction_results AS
SELECT
    b.tranche,
    b.announced_on,
    b.block_name,
    s.state_name AS state,
    string_agg(co.commodity_name, ', ' ORDER BY co.commodity_name) AS minerals,
    b.concession_type,
    c.company_name AS preferred_bidder,
    c.company_type AS bidder_type,
    b.final_price_offer_pct
FROM block_auction b
JOIN state s ON s.state_id = b.state_id
JOIN mining_company c ON c.company_id = b.preferred_bidder_id
JOIN block_auction_commodity bc ON bc.block_id = b.block_id
JOIN commodity co ON co.commodity_id = bc.commodity_id
GROUP BY b.block_id, s.state_name, c.company_name, c.company_type;
COMMENT ON VIEW v_auction_results IS 'Auctioned critical-mineral blocks with state, minerals and preferred bidder';

-- 8h. How royalty rates changed between the 2009 and 2015 schedules (self-join)
CREATE VIEW v_royalty_change_2009_2015 AS
SELECT
    co.commodity_name,
    r15.grade,
    r09.rate_text AS rate_2009,
    r15.rate_text AS rate_2015,
    CASE
        WHEN r15.basis = r09.basis AND r15.rate_pct IS NOT NULL AND r09.rate_pct IS NOT NULL
            THEN r15.rate_pct - r09.rate_pct
    END AS change_pct_points,
    CASE
        WHEN r15.basis = r09.basis AND r15.rate_rs IS NOT NULL AND r09.rate_rs IS NOT NULL
            THEN r15.rate_rs - r09.rate_rs
    END AS change_rs
FROM royalty_rate r15
JOIN royalty_rate r09
  ON r09.commodity_id = r15.commodity_id AND r09.grade = r15.grade AND r09.schedule_year = 2009
JOIN commodity co ON co.commodity_id = r15.commodity_id
WHERE r15.schedule_year = 2015;
COMMENT ON VIEW v_royalty_change_2009_2015 IS 'Royalty rate per mineral grade in the 2009 and 2015 schedules';

