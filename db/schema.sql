-- 7a. Keep mine.geom in step with latitude/longitude
CREATE FUNCTION fn_mine_set_geom() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.geom := ST_SetSRID(ST_MakePoint(NEW.longitude, NEW.latitude), 4326);
    RETURN NEW;
END $$;

CREATE TRIGGER trg_mine_set_geom
    BEFORE INSERT OR UPDATE OF latitude, longitude ON mine
    FOR EACH ROW EXECUTE FUNCTION fn_mine_set_geom();

-- 7b. updated_at on every change
CREATE FUNCTION fn_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END $$;

CREATE TRIGGER trg_mine_touch BEFORE UPDATE ON mine
    FOR EACH ROW EXECUTE FUNCTION fn_touch_updated_at();
CREATE TRIGGER trg_lease_touch BEFORE UPDATE ON lease
    FOR EACH ROW EXECUTE FUNCTION fn_touch_updated_at();

-- 7c. Change log: old and new row as JSON. The key column is passed as a trigger
--     argument. Skipped while db/setup.js loads data (minerva.seeding = on).
CREATE FUNCTION fn_log_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    key_column TEXT := TG_ARGV[0];
    old_json JSONB := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
    new_json JSONB := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
BEGIN
    IF current_setting('minerva.seeding', true) = 'on' THEN
        RETURN NULL;
    END IF;
    INSERT INTO row_change_log (table_name, operation, row_key, old_row, new_row)
    VALUES (TG_TABLE_NAME, TG_OP, COALESCE(new_json, old_json) ->> key_column,
            old_json - 'geom', new_json - 'geom');
    RETURN NULL;
END $$;

CREATE TRIGGER trg_log_change AFTER INSERT OR UPDATE OR DELETE ON mine
    FOR EACH ROW EXECUTE FUNCTION fn_log_change('mine_id');
CREATE TRIGGER trg_log_change AFTER INSERT OR UPDATE OR DELETE ON lease
    FOR EACH ROW EXECUTE FUNCTION fn_log_change('lease_id');
CREATE TRIGGER trg_log_change AFTER INSERT OR UPDATE OR DELETE ON mining_company
    FOR EACH ROW EXECUTE FUNCTION fn_log_change('company_id');
CREATE TRIGGER trg_log_change AFTER INSERT OR UPDATE OR DELETE ON production
    FOR EACH ROW EXECUTE FUNCTION fn_log_change('prod_id');

-- 7d. A mine's lease must belong to the same company as the mine
CREATE FUNCTION fn_mine_lease_company() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.lease_id IS NOT NULL AND NEW.company_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM lease WHERE lease_id = NEW.lease_id AND company_id = NEW.company_id
    ) THEN
        RAISE EXCEPTION 'Lease % is not held by company % (mine %)', NEW.lease_id, NEW.company_id, NEW.mine_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_mine_lease_company
    BEFORE INSERT OR UPDATE OF lease_id, company_id ON mine
    FOR EACH ROW EXECUTE FUNCTION fn_mine_lease_company();

