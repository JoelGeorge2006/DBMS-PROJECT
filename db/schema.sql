CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;

DROP SCHEMA IF EXISTS minerva CASCADE;
CREATE SCHEMA minerva;
COMMENT ON SCHEMA minerva IS 'MINERVA: Indian mineral resources, mines, leases and public mining statistics';
SET search_path = minerva, extensions;

-- ----------------------------------------------------------------------------
-- 1. ENUMERATED TYPES (a fixed set of values, checked by the database)
-- ----------------------------------------------------------------------------
CREATE TYPE mine_status AS ENUM ('Operational', 'Under Maintenance', 'Expiring', 'Revoked', 'Closed', 'Unknown');
CREATE TYPE mine_kind AS ENUM ('Opencast', 'Underground', 'Mixed', 'Unknown');
CREATE TYPE location_precision AS ENUM ('exact', 'approximate', 'district');
CREATE TYPE company_kind AS ENUM ('Central PSU', 'State PSU', 'Private', 'Joint Venture', 'Unknown');
CREATE TYPE commodity_category AS ENUM ('Metallic', 'Non-metallic', 'Fuel', 'Atomic', 'Gemstone');
-- pct_asp: % of average sale price; pct_metal_price: % of LME/LBMA price of contained metal
CREATE TYPE royalty_basis AS ENUM ('pct_asp', 'pct_metal_price', 'rs_per_tonne', 'other');
-- ML: mining lease; CL: composite licence (exploration followed by mining)
CREATE TYPE concession_kind AS ENUM ('ML', 'CL');
CREATE TYPE user_role AS ENUM ('admin', 'inspector', 'surveyor', 'viewer');

-- ----------------------------------------------------------------------------
-- 2. REFERENCE TABLES
-- ----------------------------------------------------------------------------
CREATE TABLE data_source (
    source_id    SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key   TEXT NOT NULL UNIQUE,
    name         TEXT NOT NULL,
    publisher    TEXT,
    url          TEXT,
    licence      TEXT NOT NULL,
    retrieved_on DATE
);
COMMENT ON TABLE data_source IS 'Where each record came from, and under which licence';

CREATE TABLE state (
    state_id           SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    state_name         TEXT NOT NULL UNIQUE,
    is_union_territory BOOLEAN NOT NULL DEFAULT FALSE
);
COMMENT ON TABLE state IS 'States and union territories of India';

CREATE TABLE location (
    location_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_id      SMALLINT NOT NULL REFERENCES state ON DELETE RESTRICT,
    district      TEXT NOT NULL,
    craton_region TEXT,
    latitude      DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude     DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT uq_location_state_district UNIQUE (state_id, district)
);
COMMENT ON TABLE location IS 'Districts (with a centre point); craton is NULL when not classified';

CREATE TABLE commodity (
    commodity_id   SMALLINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    commodity_name TEXT NOT NULL UNIQUE,
    category       commodity_category NOT NULL,
    is_critical    BOOLEAN NOT NULL DEFAULT FALSE
);
COMMENT ON TABLE commodity IS 'Mineral commodities; links mines, production, reserves, royalty rates and auctions';
COMMENT ON COLUMN commodity.is_critical IS 'On the Ministry of Mines list of 30 critical minerals (2023)';

CREATE TABLE mining_company (
    company_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name      TEXT NOT NULL UNIQUE,
    company_type      company_kind NOT NULL DEFAULT 'Unknown',
    registered_office TEXT
);
COMMENT ON TABLE mining_company IS 'Lessees, operators and auction bidders';

-- ----------------------------------------------------------------------------
-- 3. MINES, LEASES AND PRODUCTION
-- ----------------------------------------------------------------------------
CREATE TABLE lease (
    lease_id               TEXT PRIMARY KEY,
    company_id             INTEGER NOT NULL REFERENCES mining_company ON DELETE CASCADE,
    execution_date         DATE NOT NULL,
    valid_till             DATE NOT NULL,
    royalty_rate_pct       NUMERIC(5,2) NOT NULL CHECK (royalty_rate_pct BETWEEN 0 AND 100),
    lease_area_hectares    NUMERIC(12,2) NOT NULL CHECK (lease_area_hectares > 0),
    forest_clearance_stage TEXT NOT NULL DEFAULT 'Stage-II Approved',
    cto_valid_till         DATE NOT NULL,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_lease_validity CHECK (valid_till > execution_date)
);
COMMENT ON TABLE lease IS 'Mining lease agreements and clearances (sample records only)';

CREATE TABLE mineral (
    mineral_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mineral_name   TEXT NOT NULL UNIQUE,
    mineral_type   TEXT NOT NULL,
    commodity_id   SMALLINT NOT NULL REFERENCES commodity ON DELETE RESTRICT,
    fe_pct         NUMERIC(5,2) CHECK (fe_pct BETWEEN 0 AND 100),
    sio2_pct       NUMERIC(5,2) CHECK (sio2_pct BETWEEN 0 AND 100),
    al2o3_pct      NUMERIC(5,2) CHECK (al2o3_pct BETWEEN 0 AND 100),
    phosphorus_pct NUMERIC(5,2) CHECK (phosphorus_pct BETWEEN 0 AND 100),
    moisture_pct   NUMERIC(5,2) CHECK (moisture_pct BETWEEN 0 AND 100)
);
COMMENT ON TABLE mineral IS 'Mineral grades found at mines; assay columns are NULL when no typical grade is recorded';

CREATE TABLE mine (
    mine_id            TEXT PRIMARY KEY,
    mine_name          TEXT NOT NULL,
    location_id        INTEGER NOT NULL REFERENCES location ON DELETE RESTRICT,
    company_id         INTEGER REFERENCES mining_company ON DELETE SET NULL,
    lease_id           TEXT UNIQUE REFERENCES lease ON DELETE SET NULL,
    status             mine_status NOT NULL,
    mine_type          mine_kind NOT NULL DEFAULT 'Unknown',
    latitude           DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude          DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    geom               geometry(Point, 4326) NOT NULL,
    location_precision location_precision NOT NULL DEFAULT 'exact',
    source_id          SMALLINT NOT NULL REFERENCES data_source ON DELETE RESTRICT,
    source_ref         TEXT,
    source_url         TEXT,
    is_sample          BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE mine IS 'Mines (OpenStreetMap, Wikidata and 8 sample records); company and lease are optional';
COMMENT ON COLUMN mine.geom IS 'PostGIS point set from latitude/longitude by trigger trg_mine_set_geom';

